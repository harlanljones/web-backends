    (13,'Movies','movies'),(14,'Office','office'),
    (15,'Pet','pet'),(16,'Health','health'),
    (17,'Outdoors','outdoors'),(18,'Industrial','industrial'),
    (19,'Jewelry','jewelry'),(20,'Baby','baby'),
    (21,'Software','software'),(22,'Gifts','gifts'),
    (23,'Stationery','stationery'),(24,'Art','art'),
    (25,'Crafts','crafts');

COMMIT;
